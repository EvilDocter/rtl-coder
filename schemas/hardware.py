"""Comprehensive Pydantic Schemas for Hardware Lifecycle Artefacts."""

from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Literal, Optional, Union
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# 1. Specification Analyst Schemas
# ---------------------------------------------------------------------------

class PortDirection(str, Enum):
    INPUT = "input"
    OUTPUT = "output"
    INOUT = "inout"


class ResetType(str, Enum):
    SYNCHRONOUS = "synchronous"
    ASYNCHRONOUS = "asynchronous"


class SignalPort(BaseModel):
    name: str = Field(..., description="Signal identifier")
    direction: PortDirection = Field(..., description="input, output, or inout")
    width_bits: int = Field(default=1, ge=1, description="Bus width in bits")
    description: str = Field(default="", description="Functional purpose of the signal")


class ClockConfig(BaseModel):
    clock_name: str = Field(default="clk")
    edge: Literal["posedge", "negedge"] = "posedge"
    frequency_mhz: Optional[float] = None


class ResetConfig(BaseModel):
    signal_name: str = Field(default="rst_n")
    active_level: Literal["low", "high"] = "low"
    type: ResetType = ResetType.SYNCHRONOUS


class ParameterConfig(BaseModel):
    name: str
    default_value: Union[str, int]
    description: str = ""


class Requirements(BaseModel):
    """Structured requirements produced by Specification Analyst."""
    module_name: str
    summary: str
    clocking: ClockConfig = Field(default_factory=ClockConfig)
    resets: List[ResetConfig] = Field(default_factory=list)
    ports: List[SignalPort] = Field(default_factory=list)
    parameters: List[ParameterConfig] = Field(default_factory=list)
    functional_requirements: List[str] = Field(default_factory=list)
    corner_cases: List[str] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# 2. Architect Schemas
# ---------------------------------------------------------------------------

class InternalRegister(BaseModel):
    name: str
    width_bits: int
    reset_value: str = "0"
    description: str = ""


class InternalSignal(BaseModel):
    name: str
    width_bits: int = 1
    type: Literal["wire", "reg"] = "wire"
    description: str = ""


class FSMTransition(BaseModel):
    to_state: str
    condition: str


class FSMState(BaseModel):
    state_name: str
    encoding: Optional[str] = None
    transitions: List[FSMTransition] = Field(default_factory=list)
    actions: List[str] = Field(default_factory=list)


class DatapathBlock(BaseModel):
    name: str
    operation: str
    inputs: List[str] = Field(default_factory=list)
    outputs: List[str] = Field(default_factory=list)


class MicroArchitecture(BaseModel):
    """Detailed micro-architecture plan produced by Architect Agent."""
    module_name: str
    architecture_overview: str
    internal_registers: List[InternalRegister] = Field(default_factory=list)
    internal_signals: List[InternalSignal] = Field(default_factory=list)
    fsm_states: List[FSMState] = Field(default_factory=list)
    datapath_blocks: List[DatapathBlock] = Field(default_factory=list)
    control_logic: List[str] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# 3. RTL Coder Schemas
# ---------------------------------------------------------------------------

class RTLArtefact(BaseModel):
    """Synthesizable RTL code generated by RTL Coder."""
    module_name: str
    language: Literal["verilog", "systemverilog"] = "verilog"
    top_module: str
    rtl_code: str = Field(..., description="Complete synthesizable RTL source")
    design_notes: str = ""
    file_path: Optional[Path] = None


# ---------------------------------------------------------------------------
# 4. Verification Engineer Schemas
# ---------------------------------------------------------------------------

class TestScenario(BaseModel):
    name: str
    description: str
    stimulus_type: Literal["directed", "constrained_random", "corner_case"] = "directed"


class VerificationPlan(BaseModel):
    """Testbench collateral generated by Verification Engineer."""
    testbench_type: Literal["cocotb", "verilog"] = "verilog"
    top_module: str
    testbench_code: str = Field(..., description="Executable self-checking testbench")
    assertions: List[str] = Field(default_factory=list)
    test_scenarios: List[TestScenario] = Field(default_factory=list)
    coverage_points: List[str] = Field(default_factory=list)
    file_path: Optional[Path] = None


# ---------------------------------------------------------------------------
# 5. Reviewer Schemas
# ---------------------------------------------------------------------------

class DefectCategory(str, Enum):
    SYNTAX = "SYNTAX"
    FUNCTIONAL = "FUNCTIONAL"
    LINT = "LINT"
    SYNTHESIS = "SYNTHESIS"
    TIMING = "TIMING"


class DefectSeverity(str, Enum):
    CRITICAL = "CRITICAL"
    ERROR = "ERROR"
    WARNING = "WARNING"


class ReviewDefect(BaseModel):
    category: DefectCategory
    severity: DefectSeverity
    file: Optional[str] = None
    line: Optional[int] = None
    message: str
    context: Optional[str] = None


class ReviewFinding(BaseModel):
    """Review report summarizing EDA tool results."""
    status: Literal["PASS", "FAIL"]
    summary: str
    compilation_clean: bool = True
    simulation_clean: bool = True
    lint_clean: bool = True
    synthesis_clean: bool = True
    defects: List[ReviewDefect] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# 6. Reflection Schemas
# ---------------------------------------------------------------------------

class FaultClassification(str, Enum):
    RTL_BUG = "RTL_BUG"
    TESTBENCH_BUG = "TESTBENCH_BUG"
    SCRIPT_ERROR = "SCRIPT_ERROR"
    SPEC_AMBIGUITY = "SPEC_AMBIGUITY"


class CorrectionTask(BaseModel):
    """Root cause diagnosis and targeted correction instructions."""
    root_cause_analysis: str
    target_agent: Literal["rtl_coder", "verification_engineer", "script_engineer", "architect"]
    fault_classification: FaultClassification
    specific_corrections: List[str] = Field(default_factory=list)
    requires_human_escalation: bool = False
    escalation_reason: Optional[str] = None
